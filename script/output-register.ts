import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import ts from "typescript";

function files(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap(e =>
    e.isDirectory() ? files(join(dir, e.name)) : /\.tsx?$/.test(e.name) ? [join(dir, e.name)] : []).sort();
}
const clean = (value: string) => value.replace(/\|/g, "\\|").replace(/\s+/g, " ");

export function outputRegister() {
  const routes: string[][] = [], consumers: string[][] = [], exports: string[][] = [], jsonExports: string[][] = [];
  for (const path of [...files("server"), ...files("client/src")]) {
    const source = ts.createSourceFile(path, readFileSync(path, "utf8"), ts.ScriptTarget.Latest, true, path.endsWith("tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS);
    function visit(node: ts.Node) {
      if (path.startsWith("server/") && ts.isCallExpression(node) && ts.isPropertyAccessExpression(node.expression) &&
        ["get", "post", "put", "patch", "delete"].includes(node.expression.name.text) &&
        ["app", "router"].includes(node.expression.expression.getText(source))) {
        const url = node.arguments[0]?.getText(source) ?? "DYNAMIC";
        routes.push([node.expression.name.text.toUpperCase(), url, path]);
      }
      if (path.startsWith("client/") && (ts.isStringLiteralLike(node) || ts.isTemplateExpression(node)) &&
        node.getText(source).includes("/api/")) {
        consumers.push([path, node.getText(source)]);
      }
      if (path.startsWith("client/") && (ts.isJsxOpeningElement(node) || ts.isJsxSelfClosingElement(node)) &&
        node.tagName.getText(source) === "DownloadDataButton") {
        const attr = (name: string) => {
          const a = node.attributes.properties.find(p => ts.isJsxAttribute(p) && p.name.getText(source) === name);
          return a && ts.isJsxAttribute(a) ? a.initializer?.getText(source) ?? "MISSING" : "MISSING";
        };
        exports.push([path, attr("filename"), attr("rows"), attr("kind")]);
      }
      if (path.startsWith("client/") && (ts.isJsxOpeningElement(node) || ts.isJsxSelfClosingElement(node)) &&
        node.tagName.getText(source) === "DownloadJsonButton") {
        const attr = (name: string) => {
          const a = node.attributes.properties.find(p => ts.isJsxAttribute(p) && p.name.getText(source) === name);
          return a && ts.isJsxAttribute(a) ? a.initializer?.getText(source) ?? "MISSING" : "MISSING";
        };
        jsonExports.push([path, attr("filename"), attr("payload"),
          `Central download-data-button writer; evidence ${attr("kind")}; validator ${attr("validatePayload")}; lossless data envelope + interpretation + SHA-256 payload identity`]);
      }
      node.forEachChild(visit);
    }
    visit(source);
  }
  const table = (headers: string[], rows: string[][]) => [
    `| ${headers.join(" | ")} |`, `| ${headers.map(() => "---").join(" | ")} |`,
    ...rows.map(row => `| ${row.map(clean).join(" | ")} |`), "",
  ].join("\n");
  return [
    "# System output and consumer register", "",
    "Generated by `npx tsx script/output-register.ts`. CI rejects a stale register.",
    "This inventories source-level registrations and API references, not runtime reachability or scientific validation.",
    "Parameterized URLs remain explicit. Repeated references are retained; not every reference is a network request.", "",
    "## Interpretation and authority", "",
    "- Published scenario references: external published scenarios, not a dashboard forecast.",
    "- `/api/projection*`: legacy diagnostics, including unsupported climate response and residual-threshold conventions; the default dashboard does not mount them.",
    "- `/api/cv/*`: descriptive valuation/history or retrospective research. The public valuation filter removes unsupported physical claims.",
    "- `/api/calculation/*`, `/api/emissions/*` and `/api/research/*`: readiness, candidate evidence and research contracts; successful execution is not promotion.",
    "- `/api/data/*`, `/api/indicators/*`, `/api/financial-data/*`, `/api/analysis/*`: data, provenance, review or archived results. Historical selectors are request-scoped, not a global historical mode.",
    "- `/api/news/*`: source-limited descriptive news analysis.",
    "- Mutation routes remain registered for operator workflows but are restricted by the public-write guard. Registration does not grant permission.",
    "- Build/health endpoints report runtime identity and health, not scientific acceptance.", "",
    "## Registered HTTP handlers", "",
    table(["Method", "Path expression", "Implementation"], routes),
    "## Frontend API references", "",
    table(["Consumer", "API expression"], consumers),
    "## Spreadsheet exports", "",
    "Each export contains an Interpretation worksheet. Its timestamp is not an input vintage. Data rows remain unchanged.",
    "The required evidence class is enforced by TypeScript and an AST coverage test; alternate client writers require review.", "",
    table(["Consumer", "Filename expression", "Rows expression", "Evidence class"], exports),
    "## Qualified JSON exports", "",
    "These are separate supplemental contracts, not additional original1001 spreadsheet slots. Their own source/cutoff/units/limitations remain in the exported payload.", "",
    table(["Consumer", "Filename expression", "Payload", "Semantic contract"], jsonExports),
    "## Coverage boundaries", "",
    "This register covers static Express app/router method registrations, frontend API string/template references, DownloadDataButton controls and qualified DownloadJsonButton controls. Both download formats use the central writer and mandatory evidence contract.",
    "It does not certify dynamically constructed routes, external operator reports, Python research files or every field in arbitrary API JSON.",
    "Read the frontend claim register and public valuation contract alongside this census. Full Stage 1 acceptance still requires field-level review of legacy consumers.",
    "",
  ].join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync("docs/System_Output_Register.md", outputRegister());
}
